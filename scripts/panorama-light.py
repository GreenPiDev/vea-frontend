#!/usr/bin/env python3
"""Generates src/components/3d/outdoorPanoramaLight.ts from the panoramas in public/panoramas/.

For each panorama: a 16 x 8 grid of mean *linear* RGB radiance (equirectangular cells, row 0 = top) used for
the windows' soft daylight (windowLight.ts), plus the sun's direction in texture space (the centroid of the
brightest sky blob) for the sun patches. Re-run after adding or replacing a panorama:

    python3 scripts/panorama-light.py

Needs Pillow + numpy. Direction convention matches three.js equirectUv(): u = atan(z, x) / 2pi + 0.5,
v = asin(y) / pi + 0.5 (v = 1 at the top), so phi = (u - 0.5) * 2pi and elevation = (v - 0.5) * pi.
"""
import math
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PANORAMAS = ["garden", "seaside", "city", "park"]
GRID_W, GRID_H = 16, 8
# A sun needs a compact blob at full brightness; an overcast sky has none (city).
SUN_MIN_LUMA = 0.97
SUN_MIN_PIXELS = 30


def linear(img):
    return np.where(img <= 0.04045, img / 12.92, ((img + 0.055) / 1.055) ** 2.4)


def analyse(name):
    im = Image.open(ROOT / "public" / "panoramas" / f"{name}.jpg").convert("RGB")
    small = np.asarray(im.resize((1024, 512), Image.BILINEAR), dtype=np.float64) / 255
    lin = linear(small)
    grid = lin.reshape(GRID_H, 512 // GRID_H, GRID_W, 1024 // GRID_W, 3).mean(axis=(1, 3))

    luma = lin @ np.array([0.2126, 0.7152, 0.0722])
    sky = luma[:256]
    iy, ix = np.unravel_index(np.argmax(sky), sky.shape)
    ys, xs = np.nonzero(sky > SUN_MIN_LUMA * sky.max())
    near = (np.abs(ys - iy) < 20) & (np.abs(xs - ix) < 20)
    sun = None
    if sky.max() > SUN_MIN_LUMA and near.sum() >= SUN_MIN_PIXELS:
        u = (xs[near].mean() + 0.5) / 1024
        v = 1 - (ys[near].mean() + 0.5) / 512
        sun = ((u - 0.5) * 2 * math.pi, (v - 0.5) * math.pi)
    return grid, sun


def main():
    lines = [
        "// GENERATED by scripts/panorama-light.py — do not edit by hand; re-run the script after changing a panorama.",
        "// Per panorama: GRID_W x GRID_H mean linear-RGB radiance (row 0 = top, column 0 = u 0), and the sun's",
        "// texture-space direction (phi = atan(z, x), elevation, radians) or null for an overcast sky.",
        "",
        f"export const PANORAMA_LIGHT_GRID_W = {GRID_W};",
        f"export const PANORAMA_LIGHT_GRID_H = {GRID_H};",
        "",
        "export interface PanoramaLight {",
        "  /** GRID_W * GRID_H * 3 floats, row-major from the top-left. */",
        "  grid: number[];",
        "  sun: { phi: number; elevation: number } | null;",
        "}",
        "",
        "export const PANORAMA_LIGHT: Record<string, PanoramaLight> = {",
    ]
    for name in PANORAMAS:
        grid, sun = analyse(name)
        flat = ", ".join(f"{v:.4f}" for v in grid.reshape(-1))
        sun_ts = "null" if sun is None else f"{{ phi: {sun[0]:.4f}, elevation: {sun[1]:.4f} }}"
        lines.append(f"  {name}: {{")
        lines.append(f"    grid: [{flat}],")
        lines.append(f"    sun: {sun_ts},")
        lines.append("  },")
    lines.append("};")
    out = ROOT / "src" / "components" / "3d" / "outdoorPanoramaLight.ts"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
